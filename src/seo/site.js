export function applySeo(html, key) {
  if (!html.includes("<!--seo:start-->") || !html.includes("<!--seo-body:start-->")) {
    throw new Error("SEO markers are missing from index.html");
  }

  const next = html
    .replace(
      /<!--seo:start-->[\s\S]*?<!--seo:end-->/,
      `<!--seo:start-->\n${headHtml(key)}\n    <!--seo:end-->`,
    )
    .replace(
      /<!--seo-body:start-->[\s\S]*?<!--seo-body:end-->/,
      `<!--seo-body:start-->${bodyHtml(key)}<!--seo-body:end-->`,
    );

  const canonicalTag = `<link rel="canonical" href="${pages[key].canonical}" />`;
  if (!next.includes(canonicalTag)) {
    throw new Error(`Canonical was not written for ${key}`);
  }

  return next;
}
