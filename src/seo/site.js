function articleSnapshot(article) {
  const blocks = article.blocks
    .map((block) => {
      if (block.type === "h2") return `<h2>${esc(block.text)}</h2>`;
      if (block.type === "ul") {
        return `<ul>${block.items.map((item) => `<li>${esc(item)}</li>`).join("")}</ul>`;
      }
      return `<p>${esc(block.text)}</p>`;
    })
    .join("");

  return `<main style="font-family:Georgia,serif;background:#fff7ef;color:#3b2418;padding:32px 20px 64px;">
      <article style="max-width:760px;margin:0 auto;">
        <p><a href="/">Home</a> / ${esc(article.crumb)}</p>
        <h1>${esc(article.h1)}</h1>
        <p>${esc(article.intro)}</p>
        ${blocks}
        <h2>${esc(article.related.title)}</h2>
        <p>${esc(article.related.text)}</p>
        <p><a href="${esc(article.related.href)}">${esc(article.related.label)}</a></p>
      </article>
    </main>`;
}

