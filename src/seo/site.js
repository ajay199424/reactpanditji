export function getServicePath(service) {
  const text = `${service?.titleEnglish || ""} ${service?.titleHindi || ""}`.toLowerCase();
  if (text.includes("kaal sarp") || text.includes("कालसर्प")) {
    return "/kaal-sarp-dosh-puja";
  }
  if (text.includes("mangal bhat") || text.includes("मंगल भात")) {
    return "/mangal-bhat-puja";
  }
  return "";
}

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

